// Стандарт С++20:

#include <iostream>                                          // Директива препроцессора. Подключение заголовочного файла ввода-вывода;

static int conv_month(int);                                  // Прототип функции перевода лет в месяцы. Квалификатор static делает её видимой только в этом файле;

int main()                                                   // Определение главной функции, координирующей работу программы;
{
    int years_old;                                           // Объявление целочисленной знаковой переменной для хранения возраста пользователя в годах;
    std::cout << "Введите свой возраст: ";                   // Префикс std:: указывает на стандартную библиотеку. Оператор вставки << отправляет строку в поток вывода консоли;
    std::cin >> years_old;                                   // Префикс std:: указывает на стандартную библиотеку. Оператор извлечения >> забирает значение из консоли и записывает в переменную years_old;
    int month_old = conv_month(years_old);                   // Объявление переменной month_old и её одновременная инициализация результатом работы пользовательской функции;
    std::cout << "Вам " << month_old << " месяцев.\n";       // Сцепление (каскадирование) операторов << для последовательного вывода нескольких элементов в поток за один раз;
}

static int conv_month(int years)                             // Определение чистой функции перевода единиц времени;
{
    return years * 12;                                       // Функция с помощью оператора return возвращает результат арифметического умножения лет на 12 месяцев;
}


