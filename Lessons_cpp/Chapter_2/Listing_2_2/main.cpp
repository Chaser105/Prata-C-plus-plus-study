// Стандарт С++20:
#include <iostream>                                  // Директива препроцессора. Подключение заголовочного файла ввода-вывода;

int main()                                           // Определение главной функции, которая ничего не принимает и возвращает целое значение;
{
    int symbol{25};                                  // Объявление переменной типа int с одновременной унифицированной инициализацией;
    std::cout << "Слово состоит из ";                // Префикс std:: указывает компилятору, что предопределнный объект cout берется из стандартной библиотеки;
    std::cout << symbol;                             // Префикс std:: указывает компилятору, что предопределнный объект cout берется из стандартной библиотеки. Вывод числового значения переменной symbol в поток консоли (cout сам распознает тип данных);
    std::cout << " символов.\n";                     // Префикс std:: указывает компилятору, что предопределнный объект cout берется из стандартной библиотеки;
    symbol = symbol - 4;                             // Вычисление нового значения и обновление переменной symbol;
    std::cout << "Другое слово состоит из " << symbol << " символа.\n"; // Сцепление (каскадирование) операторов << для вывода нескольких элементов в поток за один раз;
}


