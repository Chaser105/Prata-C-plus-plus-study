// Стандарт С++20:

#include <iostream>                                          // Директива препроцессора. Подключение заголовочного файла ввода-вывода;

static void The_time(int, int);                              // Прототип void-функции, принимающей два целочисленных значения int и ничего не возвращающей. Квалификатор static делает её видимой только в этом файле;

int main()                                                   // Определение главной функции, координирующей работу программы;
{
    int hour, minute;                                        // Объявление целочисленных знаковых переменных для хранения часов и минут;
    std::cout << "Введите время в часах: ";                  // Префикс std:: указывает на стандартную библиотеку. Оператор вставки << отправляет строку в поток вывода консоли;
    std::cin >> hour;                                        // Префикс std:: указывает на стандартную библиотеку. Оператор извлечения >> забирает значение часов из консоли;
    std::cout << "Введите время в минутах: ";                // Вывод приглашения к вводу минут в поток консоли;
    std::cin >> minute;                                      // Извлечение введенного значения минут из консоли в переменную minute;
    The_time(hour, minute);                                  // Вызов пользовательской void-функции с передачей двух аргументов для итогового вывода на экран;
}

static void The_time(int h, int m)                           // Определение пользовательской void-функции отображения времени;
{
    std::cout << "Время: " << h << ":" << m << "\n";         // Сцепление (каскадирование) операторов << для вывода отформатированного времени в поток консоли;
}

