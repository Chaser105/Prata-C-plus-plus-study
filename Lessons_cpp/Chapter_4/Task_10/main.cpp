// Стандарт С++20

#include <iostream>                                               // Подключение заголовочного файла для работы со стандартными потоками ввода-вывода (std::cout, std::cin);
#include <format>                                                 // Подключение заголовочного файла для современного типобезопасного форматирования текста через std::format;
#include <array>                                                  // Подключение заголовочного файла для работы с фиксированным контейнером std::array и типом std::size_t;

namespace                                                         // Объявление безымянного пространства имен для ограничения видимости текущей единицей трансляции;
{
    constexpr std::size_t size{3};                                // Константа времени компиляции для задания фиксированного размера массива;
}

int main()
{
    std::array<float, size> scores_run{};                         // Объявление и инициализация нулями по умолчанию контейнера std::array из 3 элементов типа float для хранения времени забегов;

    std::cout << "Введите результат 3 забегов на 40 метров: ";    // Объект std::cout с помощью оператора << выводит приглашение пользователю для ввода данных;
    std::cin >> scores_run[0];                                    // Объект std::cin с помощью оператора >> считывает первое введенное число и записывает его в 1-й элемент массива по индексу;
    std::cin >> scores_run[1];                                    // Объект std::cin с помощью оператора >> считывает второе введенное число и записывает его во 2-й элемент массива по индексу;
    std::cin >> scores_run[2];                                    // Объект std::cin с помощью оператора >> считывает третье введенное число и записывает его в 3-й элемент массива по индексу;

    const float div_res_run = (scores_run[0] + scores_run[1] + scores_run[2]) / static_cast<float>(scores_run.size()); // Вычисление среднего арифметического с явным приведением размера массива к типу float через static_cast и сохранение в константную переменную;

    std::cout << std::format("Результат 1 забега {:.3f} сек\n"     // Объект std::cout с помощью оператора << выводит отформатированную строку, сформированную функцией std::format (спецификатор {:.3f} округляет числа с плавающей точкой до 3 знаков после запятой);
                                    "Результат 2 забега {:.3f} сек\n"
                                    "Результат 3 забега {:.3f} сек\n"
                             "Средний результат забегов {:.3f} сек\n",
    scores_run[0], scores_run[1], scores_run[2], div_res_run);// Передача значений элементов массива по индексам и вычисленного среднего значения в функцию форматирования;
}



