// Стандарт С++20:

#include <iostream>
#include <format>
#include <string>                                               // Подключение заголовочного файла для применения класса string;
#include <cstdint>                                              // Подключение типов данных с гарантированным фиксированным размером в битах;

int main()
{
    std::string first_name{}, last_name{};                      // Инициализация двух пустых объектов строк для хранения имени и фамилии;
    char grade_requested{};                                     // Инициализация пустой переменной символьного типа для хранения желаемой оценки;
    std::uint16_t age{0};                                       // Инициализация целочисленной двухбайтовой переменной для корректного считывания возраста как числа;

    std::cout << "Введите свое имя: ";
    std::getline(std::cin, first_name);                   // Функция getline считывает строку с пробелами в объект first_name до символа \n, который затем автоматически отбрасывается;

    std::cout << "Введите свою фамилию: ";
    std::getline(std::cin, last_name);                    // Функция getline считывает строку с пробелами в объект last_name, полностью очищая буфер от символа \n;

    std::cout << "Какую оценку, в виде буквы, вы заслуживаете? ";
    std::cin >> grade_requested;                                // Предопределенный объект cin считывает один символ (английскую букву) в переменную grade_requested;

    grade_requested = static_cast<char>(grade_requested + 1);   // Операция целочисленного расширения (integral promotion): к ASCII-коду символа прибавляется единица. вное приведение типов static_cast<char> безопасно возвращает получившееся число обратно в символьный тип char;

    std::cout << "Сколько вам лет? ";
    std::cin >> age;                                            // Предопределенный объект cin считывает числовое значение возраста в переменную age;

    std::cout << std::format("Имя: {}, {}\nОценка: {}\nВозраст: {}\n", // Предопределенный объект cout с помощью оператора << выводит строку, отформатированную с помощью std::format;
            last_name, first_name, grade_requested, age);
}




