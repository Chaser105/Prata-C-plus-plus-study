// Стандарт С++20

#include <iostream>                                               // Подключение заголовочного файла для работы со стандартными потоками ввода-вывода (std::cout);
#include <string>                                                 // Подключение заголовочного файла для работы с безопасным строковым типом std::string;
#include <format>                                                 // Подключение заголовочного файла для современного типобезопасного форматирования текста через std::format;
#include <cstdint>                                                // Подключение заголовочного файла для использования целочисленных типов фиксированной ширины (std::uint32_t);
#include <vector>                                                 // Подключение заголовочного файла для работы с динамическим контейнером std::vector (выделение памяти в куче с автоматическим управлением);

namespace                                                         // Объявление безымянного пространства имен для ограничения видимости текущей единицей трансляции;
{
    struct CandyBar                                               // Объявление структуры типа CandyBar с тремя полями и инициализацией значений по умолчанию;
    {
        std::string box_name{};                                   // Поле для хранения названия коробки сладостей (инициализация пустой строкой по умолчанию);
        float box_weight{0.0f};                                   // Поле для хранения веса коробки с дробной частью (инициализация нулем по умолчанию);
        std::uint32_t box_calories{0};                            // Поле для хранения количества калорий без знака фиксированного размера 32 бита (инициализация нулем по умолчанию);
    };
}

int main()
{
    std::vector<CandyBar> snack                                   // Инициализация класса-контейнера std::vector (1-й уровень скобок);
    {
        {.box_name = "Mocha Munch", .box_weight = 2.3f, .box_calories = 350},       // Инициализация 1-й структуры CandyBar (2-й уровень скобок);
        {.box_name = "Chocolate cookies", .box_weight = 12.7f, .box_calories = 540},// Инициализация 2-й структуры CandyBar (2-й уровень скобок);
        {.box_name = "Fruit jelly", .box_weight = 5.6f, .box_calories = 428}        // Инициализация 3-й структуры CandyBar (2-й уровень скобок);
    };

    std::cout << std::format("Коробка конфет: {}\nВес: {} кг\nКалорийность: {} кал.\n\n", // Объект std::cout с помощью оператора << выводит отформатированную строку, сформированную функцией std::format.
 snack[0].box_name, snack[0].box_weight, snack[0].box_calories);                 // Обращение к 1-му элементу массива snack по индексу [0] и передача значений его полей через оператор принадлежности (.);

    std::cout << std::format("Коробка печенье: {}\nВес: {} кг\nКалорийность: {} кал.\n\n",// Объект std::cout с помощью оператора << выводит отформатированную строку, сформированную функцией std::format.
    snack[1].box_name, snack[1].box_weight, snack[1].box_calories);              // Обращение ко 2-му элементу массива snack по индексу [1] и передача значений его полей через оператор принадлежности (.);

    std::cout << std::format("Коробка желе: {}\nВес: {} кг\nКалорийность: {} кал.\n\n",   // Объект std::cout с помощью оператора << выводит отформатированную строку, сформированную функцией std::format.
    snack[2].box_name, snack[2].box_weight, snack[2].box_calories);              // Обращение к 3-му элементу массива snack по индексу [2] и передача значений его полей через оператор принадлежности (.);
}



