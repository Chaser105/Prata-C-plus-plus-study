// Стандарт С++20:

#include <iostream>
#include <format>
#include <string>                                       // Подключение заголовочного файла для применения класса std::string для работы со строками;
#include <memory>                                       // Подключение заголовочного файла для работы с динамической памятью через умные указаетли;

namespace
{
    struct inflatable                                   // Объявление структуры типа inflatable, состоящего из 3 полей;
    {
        std::string name{};
        float volume{0.0f};
        double price{0.0};
    };
}

int main()
{
    const auto ps = std::make_unique<inflatable>();                // Указателю типа структуры присваивается адрес выделенной памяти (в куче) под динамическую структуру;
    std::cout << "Введите имя надувного изделия: ";
    std::getline(std::cin, ps->name);                        // Объект cin применяет метод .get() для записи строки в массив, обращаясь к нему по адресу структуры через оператор членства-указателя;
    std::cout << "Введите объем в кубических футах: ";
    std::cin >> ps->volume;                            // Объект cin с помощью оператора >> вводит значение с клавиатуры в поле volume, обращаясь к нему через разыменованный указатель структуры через оператор принадлежности;
    std::cout << "Введите цену: ";
    std::cin >> ps->price;                               // Объект cin с помощью оператора >> вводит значение с клавиатуры в поле price, обращаясь к нему по адресу структуры через оператор членства-указателя;
    std::cout << std::format("Имя {}\n", ps->name);           // Объект cout с помощью оператора << выводит строку с содержимым массива, обращаясь к нему через разыменованный указатель структуры через оператор принадлежности;
    std::cout << std::format("Объем {} кубических футов\n", ps->volume ); // Объект cout с помощью оператора << выводит строку со значением, обращаясь к нему по адресу структуры через оператор членства-указателя;
    std::cout << std::format("Цена ${}\n", ps->price);          // Объект cout с помощью оператора << выводит строку со значением, обращаясь к нему по адресу структуры через оператор членства-указателя;
}