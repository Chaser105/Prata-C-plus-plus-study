// Стандарт С++20:

#include <iostream>
#include <format>
#include <string>                                       // Подключение заголовочного файла для применения класса std::string для работы со строками;
#include <memory>                                       // Подключение заголовочного файла для работы с динамической памятью через умные указатели;

namespace
{
    struct inflatable                                   // Объявление структуры типа inflatable, состоящего из 3 полей;
    {
        std::string name{};
        float volume{0.0f};
        double price{0.0};
    };
}

int main()
{
    const auto ps = std::make_unique<inflatable>();                // std::make_unique<inflatable>() — функция make_unique выделяет пространство в памяти (в куче) через new для структуры типа inflatable и выдает умный указатель. Квалификатор const защищает от случайного изменения указателя. Тип auto указывает компилятору автоматически применить тип std::unique_ptr<inflatable>;
    std::cout << "Введите имя надувного изделия: ";
    std::getline(std::cin, ps->name);                        // Функция getline(), принимая 1 аргумент - объект cin, записывает строку, введенную с клавиатуры в объект строки (2 аргумент), обращаясь к нему по адресу структуры через оператор членства-указателя;
    std::cout << "Введите объем в кубических футах: ";
    std::cin >> ps->volume;                                        // Объект cin с помощью оператора >> вводит значение с клавиатуры в поле volume, обращаясь к нему по адресу структуры через оператор членства-указателя;
    std::cout << "Введите цену: ";
    std::cin >> ps->price;                                         // Объект cin с помощью оператора >> вводит значение с клавиатуры в поле price, обращаясь к нему по адресу структуры через оператор членства-указателя;
    std::cout << std::format("Имя {}\n", ps->name);     // Объект cout с помощью оператора << выводит отформатированную строку с содержимым объекта строки, обращаясь к нему по адресу структуры через оператор членства-указателя;
    std::cout << std::format("Объем {} кубических футов\n", ps->volume ); // Объект cout с помощью оператора << выводит отформатированную строку со значением, обращаясь к нему по адресу структуры через оператор членства-указателя;
    std::cout << std::format("Цена ${}\n", ps->price);  // Объект cout с помощью оператора << выводит отформатированную строку со значением, обращаясь к нему по адресу структуры через оператор членства-указателя;
}



