// Стандарт С++20:

#include <iostream>
#include <format>
#include <cstdint>
#include <cwchar>                                       // Подключение заголовочного файла для работы с широкими С-style строками и функцией wcslen;

inline constexpr int32_t size{15};                      // Ограничение длины строки для защиты от переполнения буфера;

int main()
{
    std::setlocale(LC_ALL, "");           // Установка локали для корректного отображения и ввода кириллицы;
    wchar_t name1[size];                                // Объявление пустого массива широких символов из 15 элементов;
    wchar_t name2[size] {L"C++owboy"};                  // Инициализация массива широких символов литералом (префикс L обязателен);
    std::wcout << std::format(L"Привет! Я - {}", name2); // Оператор << передает в wcout готовую широкую текстовую строку (std::wstring), которую сгенерировала функция std::format;
    std::wcout << L"! Как тебя зовут?\n";
    std::wcin >> name1;                                 // Переопределенный объект wcin с помощью оператора >> считывает широкую строку с клавиатуры в массив name1;
    std::wcout << std::format(L"Что ж, {}, в твоем имени ", name1);    // Оператор << передает в wcout готовую широкую текстовую строку, которую сгенерировала функция std::format;
    std::wcout << std::format(L"{} букв и оно хранится\n", std::wcslen(name1)); // Функция wcslen подсчитывает количество фактических широких символов в строке, не учитывая L'\0';
    std::wcout << std::format(L"в массиве из {} байт.\n", sizeof(name1));  // Оператор sizeof определяет полный размер выделенной под массив памяти в байтах (для wchar_t в Linux это size * 4 байта);
    std::wcout << std::format(L"Твоя первая буква {}\n", name1[0]);    // Оператор << выводит один широкий символ под индексом 0 (первый символ строки);
    name2[3] = L'\0';                                                             // В массиве name2 четвертому элементу (индекс 3) присваивается значение нуль-терминатора широкого типа, искусственно обрезая строку;
    std::wcout << std::format(L"Здесь первые 3 символа моего имени: {}\n", name2); // Оператор << передает в wcout готовую широкую текстовую строку из первых 3 символов;
}



