#include <format>
#include <iostream>
#include <string>

int main()
{
    std::string name{};                      // Объявление пустого динамического строкового объекта;
    std::string dessert{};                   // Объявление пустого динамического строкового объекта;
    std::cout << std::format("Введите свое имя:\n"); // Предопределенный объект cout с помощью оператора << выводит отформатированную UTF-8 строку в поток вывода и автоматически переносит курсор на следующую строку;
    std::getline(std::cin,name);       // Функция getline считывает строку до символа новой строки \n, который потом отбрасывается, вместе с пробелами в строковый объект, при этом размер объекта становится равным под размер ввода;
    std::cout << std::format("Введите свой любимый десерт:\n");     // Предопределенный объект cout с помощью оператора << выводит UTF-8 строку в поток вывода и автоматически переносит курсор на следующую строку;
    std::getline(std::cin,dessert);    // Функция getline считывает строку до символа новой строки \n, который потом отбрасывается, вместе с пробелами в строковый объект, при этом размер объекта становится равным под размер ввода;
    std::cout << std::format("У меня есть вкусный {} для тебя, {}.\n",
        dessert, name);                                            // Предопределенный объект cout с помощью оператора << берет строковый динамический объект и безопасно форматирует текст в UTF-8 в консоль;

}



