/*
  При сдвиге адреса указателя на массив происходит сдвиг всех элементов вперед
ровно на тотже шаг. При этом сам массив в памяти остается на месте.
Работая со сдвигом необходимо предусмотреть, что если залезть за пределы массива,
можно получить данные других переменных, объектов, функций и т.п., т.е. это уже будет мусором.

  Прежде чем освобождать память от динамического массива, необходимо вернуть указатель на первый
элемент массива под индексом 0. Иначе программа аварийно заверщится.
*/


// Стандарт С++20:

#include <iostream>
#include <format>
#include <vector>

int main()
{
    std::vector<double>p3{0.2, 0.5, 0.8};            // Инициализация динамического массива типа double p3, созаданный с помощью класса-контейнера vector, который выделяет место в памяти и сам определяет размер массива. После завершения функции класс-контейнер сам освобождает память от динамического массива;
    std::cout << std::format("p3[1] это {}\n", p3[1]);  // Объект cout при помощи оператора << выводит отформатированную строку со значением элемента динамического массива под индексом 1;
    auto it = p3.begin();                            // Спецификатор auto сам определяет тип данных, компилятор смотрит на правую часть и определят как итератор типа double std::vector<double>::iterator. Вектор p3 применяет метод begin(), который привязывается к первомоу элементу массива. Данный метод применяется для создания окна обзора, чтобы можно было обращаться к отдельным элемнтам массива;
    it = it + 1;                                     // Итератор смещается на следующий адрес элемента массива типа double (с it[0] на it[1]);
    std::cout << std::format("Теперь it[0] это {} и it[1] это {}\n", it[0], it[1]); // Объект cout при помощи оператора << выводит строку со значением элемента динамического массива под индексом 0, теперь значение будет отличное от начального присваивания элементу массива p3[0] под индесом 0;
    it = it - 1;                                     // Итератор смещается назад на один элемент  массива типа double (с it[1] на it[0]);
}


