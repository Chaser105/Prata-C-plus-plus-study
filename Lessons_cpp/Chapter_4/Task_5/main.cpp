// Стандарт С++20

#include <iostream>                                               // Подключение заголовочного файла для работы со стандартными потоками ввода-вывода (std::cout);
#include <string>                                                 // Подключение заголовочного файла для работы с безопасным строковым типом std::string;
#include <format>                                                 // Подключение заголовочного файла для современного типобезопасного форматирования текста через std::format;
#include <cstdint>                                                // Подключение заголовочного файла для использования целочисленных типов фиксированной ширины (std::uint32_t);

namespace                                                         // Объявление безымянного пространства имен для ограничения видимости структуры текущей единицей трансляции (внутреннее связывание);
{
    struct CandyBar                                               // Объявление структуры типа CandyBar с тремя полями и инициализацией значений по умолчанию;
    {
        std::string box_name{};                                   // Поле для хранения названия коробки конфет (инициализация пустой строкой по умолчанию);
        float box_weight{0.0f};                                   // Поле для хранения веса коробки с дробной частью (инициализация нулем по умолчанию);
        std::uint32_t box_calories{0};                            // Поле для хранения количества калорий без знака фиксированного размера 32 бита (инициализация нулем по умолчанию);
    };
}

int main()
{
    CandyBar snack                                                // Объявление и инициализация переменной snack типа структуры CandyBar через назначенные инициализаторы;
    {
        .box_name = "Mocha Munch",                                // Явное присваивание строкового значения полю box_name по его имени;
        .box_weight = 2.3f,                                       // Явное присваивание дробного значения (типа float) полю box_weight по его имени;
        .box_calories = 350                                       // Явное присваивание целочисленного значения полю box_calories по его имени;
    };

    std::cout << std::format("Коробка конфет: {}\nВес: {} кг\nКалорийность: {} кал.\n", // Объект std::cout с помощью оператора << выводит отформатированную строку, сформированную функцией std::format;
    snack.box_name, snack.box_weight, snack.box_calories);        // Передача значений полей структуры snack в функцию форматирования через оператор принадлежности (.);
}



