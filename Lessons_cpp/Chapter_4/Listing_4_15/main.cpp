// Стандарт С++20:

#include <iostream>
#include <format>
#include <cstdint>

int main()
{
    int32_t updates = 6;
    int32_t *p_updates = &updates;                                            // Инициализация указателя, которому присваиваивается адрес переменной;
    std::cout << std::format("Значение: updates = {}, *p_updates = {}\n",  // Объект cout с помощью оператора << выводит отформатированную строку со значением переменной и значение разыменованнго указаетеля;
                         updates, *p_updates);
    std::cout << std::format("Адресс: &updates = {},  p_updates = {}\n",   // Объект cout с помощью оператора << выводит отформатированную строку и адрес в памяти (стеке) переменной и адрес переменной updates, хранящейся в памяти указателя p_updates;
                            static_cast<const void*>(&updates),
                            static_cast<const void*>(p_updates));
    *p_updates = *p_updates + 1;                                  // *p_updates + 1 - производится разыменование указателя, получаем значение переменной. К этому значению прибавляем 1 и результат присваивается в ячейку памяти по адресу, который хранится в p_updates;
    std::cout << std::format("Новое значение updates = {}\n", *p_updates);  // Объект cout с помощью оператора << выводит отформатированную строку и значение переменной, на которую указывает указатель;
}


/*
  static_cast<const void*>(&updates) необходим для std::format, чтобы временно
привести указатель к типу "сырого" адреса памяти (void*). Это сообщает функции
format, что тип int32_t* интерпретировать не нужно, а следует просто безопасно
вывести номер ячейки памяти в шестнадцатеричном формате. Т.е. не нужно функции
примянять инструкции с типом int32_t.
*/


