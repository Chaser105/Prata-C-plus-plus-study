// Стандарт С++20:

#include <iostream>
#include <format>
#include <cstdint>

int main()
{
    int32_t higgens = 5;
    int32_t *pt = &higgens;                                                             // В указатель записан адрес переменной;
    std::cout << std::format("Значение переменной higgens = {}"                  // Объект cout с помощью оператора << выводит отформатированную строку со значением переменной и адрес переменной;
                             "; Адрес переменной higgens = {}\n",
                             higgens, static_cast<const void*>(&higgens));
    std::cout << std::format("Значение указателя *pt = {}"                       // Объект cout с помощью оператора << выводит отформатированную строку со значением, полученный при разыменовании указателя и указатель, содержащий адрес переменной;
                            "; Адрес переменной higgens записанный в указатель pt = {}\n",
                            *pt, static_cast<const void*>(pt));
}


/*
  static_cast<const void*>(&higgens) необходим для std::format, чтобы временно
привести указатель к типу "сырого" адреса памяти (void*). Это сообщает функции
format, что тип int32_t* интерпретировать не нужно, а следует просто безопасно
вывести номер ячейки памяти в шестнадцатеричном формате. Т.е. не нужно функции
применять инструкции с типом int32_t.
*/


