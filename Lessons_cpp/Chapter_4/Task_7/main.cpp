// Стандарт С++20

#include <iostream>                                               // Подключение заголовочного файла для работы со стандартными потоками ввода-вывода (std::cout, std::cin);
#include <format>                                                 // Подключение заголовочного файла для современного типобезопасного форматирования текста через std::format;
#include <string>                                                 // Подключение заголовочного файла для работы с безопасным динамическим строковым типом std::string и функцией std::getline;

namespace                                                         // Объявление безымянного пространства имен для ограничения видимости текущей единицей трансляции;
{
    struct MarketAnalysis                                         // Объявление структуры типа MarketAnalysis с тремя полями и инициализацией значений по умолчанию;
    {
        std::string name_pizza{};                                 // Поле для хранения названия компании-производителя пиццы (инициализация пустой строкой по умолчанию);
        float diameter{0.0f};                                     // Поле для хранения диаметра пиццы с дробной частью (инициализация нулем по умолчанию);
        float weight{0.0f};                                       // Поле для хранения веса пиццы с дробной частью (инициализация нулем по умолчанию);
    };
}

int main()
{
    MarketAnalysis pizza{};                                       // Создание объекта структуры MarketAnalysis с гарантированной инициализацией всех полей по умолчанию через фигурные скобки {};

    std::cout << "Введи производителя пиццы: ";                   // Объект std::cout с помощью оператора << выводит приглашение к вводу названия производителя в консоль;
    std::getline(std::cin, pizza.name_pizza);               // Функция std::getline считывает всю строку целиком (включая пробелы) из потока std::cin в поле name_pizza до символа \n, который затем отбрасывается;

    std::cout << "Введите размер пиццы: ";                        // Объект std::cout с помощью оператора << выводит приглашение к вводу диаметра пиццы в консоль;
    std::cin >> pizza.diameter;                                   // Объект std::cin с помощью оператора извлечения >> считывает числовое значение с плавающей точкой в поле diameter;

    std::cout << "Введите вес пиццы: ";                           // Объект std::cout с помощью оператора << выводит приглашение к вводу веса пиццы в консоль;
    std::cin >> pizza.weight;                                     // Объект std::cin с помощью оператора извлечения >> считывает числовое значение с плавающей точкой в поле weight;

    std::cout << std::format("Производитель пиццы: {}\nРазмер: {}см\nВес: {}г\n", // Объект std::cout с помощью оператора << выводит отформатированную строку, сформированную функцией std::format.
                    pizza.name_pizza, pizza.diameter, pizza.weight);     // Передача значений полей объекта pizza через оператор принадлежности (.) в аргументы форматирования;
}




