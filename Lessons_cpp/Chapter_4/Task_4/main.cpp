// Стандарт С++20:

#include <iostream>
#include <format>
#include <string>                                                     // Подключение заголовочного файла для работы с динамическим классом-контейнером string;

int main()
{
    std::string first_name{};                                         // Безопасная инициализация пустого объекта first_name класса string. Объект контролирует выделение памяти в куче, защищая программу от переполнения буфера;
    std::string last_name{};                                          // Безопасная инициализация пустого объекта last_name класса string. На старте размер (size) и емкость (capacity) равны нулю;
    std::string name{};                                               // Объявление объекта name класса string, который будет использоваться как третья переменная для физического построения и сохранения склеенной строки в памяти;

    std::cout << "Введите свое имя: ";                                // Объект cout с помощью оператора << выводит в консоль приглашение для ввода имени;
    std::getline(std::cin, first_name);                         // Функция getline() считывает поток ввода целиком до нажатия Enter и записывает данные в объект first_name, позволяя безопасно обрабатывать имена с пробелами;

    std::cout << "Введите свою фамилию: ";                            // Объект cout с помощью оператора << выводит в консоль приглашение для ввода фамилии;
    std::getline(std::cin, last_name);                          // Функция getline() считывает поток ввода целиком вместе с пробелами и записывает результат в объект last_name, исключая сбои чтения;

    name = last_name + ", " + first_name;                             // Операция конкатенации (склеивания). С помощью оператора + строки сращиваются в нужном порядке (фамилия, запятая, пробел, имя) и результат физически сохраняется в объект name;
    std::cout << std::format("Вот информация в одной строке: {}\n", name); // Объект cout с помощью оператора << выводит отформатированную строку, подставляя значение сохраненного объекта name через шаблонизатор функции format();
}



