// Стандарт С++20

#include <iostream>
#include <format>
#include <string>
#include <cstddef>                       // Подключение заголовочного файла, где определен типа size_t;
#include <cstdint>

int main()
{
    std::string name{};                  // Объявление объекта строки;
    std::cout << "Введите свое имя: ";
    std::getline(std::cin, name);  // Функция getline() с помощью объекта cin записывает строку, введенную с клавиатуры, в объект строки;
    std::cout << "Вот ваше имя, представленное в вертикальном виде и в формате ASCII:\n";
    const std::size_t word_size{name.size()}; // Инициализация защищенной переменной, которой присваивается значение (размер строки) определенное методом .size() класса string;
    std::size_t i{0};                    // Инициализация беззнаковой переменной значением ноль (по умолчанию);
    while (i < word_size)                // Определение цикла  while. Когда переменная-счетчик станет равна значению переменной, цикл завершится;
    {
        const std::size_t start{i};      // Инициализация защищенной переменной значением, представляющей далее в программе индекс байта символа строки (самый левый байт символа);
        ++i;                             // При префиксном инкрементировании происходит сдвиг индекса на следующий байт символа;

        while (i < word_size && (static_cast<std::uint8_t>(name[i]) & 0xC0) == 0x80)  // Определение внутреннего цикла while. Когда переменная-счетчик станет равна значению переменной или при явном приведении к беззнаковому типу uint8_t элемента строки и побитовая проверка маской не равна байту 0х80, цикл завершится;
            ++i;                                                                      // При префиксном инкрементировании происходит свдиг индекса на следующий байт символа;
                                                                                      // Кириллические символы в кодировке UTF-8 состоят из 2 байт: 1-й начинается с 11......, 2-й (хвост) начинается с 10......; проверка идет слева направо, цикл перешагивает 2-й байт и останавливается на следующем 1-м байте символа, ничего не выкидывая.
                                                                                      // У всех символов от 2 до 4 байт первый байт начинается с 11......, а у остальных начинаются с 10........ Получается в этом цикле байты с 10....... просто пропускаются и в программе никак не обрабатываются только сдвигается счетчик цикла означающий сдвиг на следующий байт символа;

        std::cout << std::format("{}: ", name.substr(start, i - start)); // Метод .substr() класса string принимает 1-й аргумент — начальный индекс байта (start), и 2-й аргумент — длину вырезаемого среза в байтах (i - start: 1 для латиницы, 2 для кириллицы, 3-4 для иероглифов и эмодзи). Так мы получаем символ целиком и выводим его на экран;
        std::size_t k{start};            // Инициализация беззнаковой переменной, которой присваивается значение переменной start, которая указывает на самый левый байт символа;

        while (k < i)                    // Определение цикла  while. Если переменная k (индекс байта самого левого текущего символа) станет равной переменной i (указывает на индекс байта следующего символа или конец строки, т.е. после последнего байта), цикл завершится;
        {
            std::cout << std::format("{} ", static_cast<std::uint8_t>(name[k])); // Явное приведение типа uint8_t элемента строки для перевода символа в код согласно UTF-8. Вывод будет с каждым циклом производится побайтно;
            ++k;                         // При префиксном инкрементировании происходит сдвиг индекса (байта) текущего символа;
        }
        std::cout << '\n';
    }
}



