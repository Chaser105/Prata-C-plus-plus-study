// Стандарт С++20

#include <iostream>
#include <format>
#include <cstdint>

int main()
{
    std::int32_t a{20};
    std::int32_t b{20};
    std::cout << std::format("a = {}:  b = {}\n", a, b);
    std::cout << std::format("a++  = {}:  ++b = {}\n", a++, ++b); // К переменной а применяется постфиксное инкрементирование, т.е. сначала выведется начальное значение и сразу увеличивается на 1. К переменной b применяется префиксное инкрементирование, т.е. значение сразу увеличивается на 1 и выводится на экран;
    std::cout << std::format("a = {}:  b = {}\n", a, b);
}



