// Стандарт С++20

#include <iostream>
#include <format>
#include <cstdint>

int main()
{
    std::cout << "Введите начальное значение счетчика: ";

    std::int32_t limit{};                                   // Инициализация переменной фиксированного типа по умолчанию для инициализации переменной i начальным значением;
    std::cin >> limit;

    std::int32_t i{limit};                                  // Инициализация переменной-счетчика фиксированного типа начальным значением для цикла for:
    for (; i > 0; i--)                                      // 1 - инициализация переменной (остается путым), 2 - условие выполнения блока цикла for, 3 - выражение итерации - уменьшение на 1;
        std::cout << std::format("i = {}\n", i); // Когда переменная i станет равна 0, цикл завершится и блок цикла for пропустится. Данное выражение защищает от отрицательных значений в отличии от булевого;

    std::cout << std::format("Цикл завершен, значение переменной i = {}\n", i);
}



