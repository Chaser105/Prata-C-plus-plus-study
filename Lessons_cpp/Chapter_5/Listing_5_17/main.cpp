/*
 * КАК РАБОТАЕТ std::getline():
 * 1. Читает вообще все символы подряд (включая пробелы и табуляции), пока не упрется в стоп-символ.
 * 2. Сам стоп-символ из буфера забирается, но в итоговую строку НЕ записывается (выкидывается):
 *    - std::getline(std::cin, text);      -> стоп-символ по умолчанию Enter ('\n'). В строку не попадает.
 *    - std::getline(std::cin, text, '#'); -> стоп-символ задан вручную ('#'). Теперь Enter ('\n')
 *                                            считается как обычный символ, а выкидывается только '#'.
 */
