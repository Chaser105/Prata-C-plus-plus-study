// Стандарт С++20

#include <iostream>
#include <cstdint>

int main()
{
    constexpr std::int32_t iterations{5};        // Константа времени компиляции фиксированного типа для сравнения со значением счетчика;

    for (std::int32_t i{0}; i < iterations; i++) // Определение цикла for. 1 инициализатор фиксированного типа, 2 условие - сравнение значения счетчика со значением, 3 выражение итерации - увеличение значения счетчика на 1 (инкрементирование);
        std::cout << "C++ цикл.\n";              // Если значение счетчика меньше 5, то выполнится блок цикла for, если равно или больше, то блок цикла пропустится;

    std::cout << "С++ цикл завершен.\n";
}




