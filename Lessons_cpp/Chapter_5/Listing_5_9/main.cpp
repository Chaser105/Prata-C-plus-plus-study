// Стандарт С++20

#include <cstddef>
#include <format>
#include <iostream>
#include <string>

int main()
{
    std::cout << "Введите текст: ";
    std::string word{};                                               // Определение объекта строки;
    std::getline(std::cin, word);                               // Функция getline() принимает объект cin для ввода строки с клавиатуры в объект строки;

    // Проход 1: разворачиваем байты внутри каждого многобайтового символа UTF-8
    for (std::size_t i{0}; i < word.size(); )                         // Определение цикла for. 1 - инициализация переменной счетчика беззнакового типа, 2 - выражение сравнения. Переменная i сравнивается со значением размера строки объекта word;
    {
        const std::size_t start{i};                                   // Инициализация защищенной переменной значением, представляющей далее в программе индекс байта символа строки;
        ++i;                                                          // Префиксное инкрементирование переменной. Представляющей далее в программе переменной для сдвига на следующий байт строки;

        for (; i < word.size() && ((static_cast<unsigned char>(word[i]) & 0xC0) == 0x80); ++i) {} // Определение внутреннего цикла for. 1 - инициализатор задан во внешнем цикле, 2 - выражение сравнения, проверяется выход за границу строки, затем производится явное приведение к беззнаковому типу unsigned char элемента строки и побитовая проверка маской, 3 - выражение итерации с увеличением на 1 с каждым циклом.
                                                                                                  // Кириллические символы в кодировке UTF-8 состоят из 2 байт: 1-й начинается с 11......, 2-й (хвост) начинается с 10......; проверка идет слева направо, цикл перешагивает 2-й байт и останавливается на следующем 1-м байте символа, ничего не выкидывая.
                                                                                                  // У всех символов от 2 до 4 байт первый байт начинается с 11......, а у остальных начинаются с 10........ Получается в этом цикле байты с 10....... просто пропускаются и в программе никак не обрабатываются только сдвигается счетчик цикла означающий сдвиг на следующий байт символа;
        for (std::size_t left{start}, right{i}; left < right; ++left)   // Низкоуровневый обмен байтов внутри одного символа (от start до i)
        {
            --right;
            const char temp{word[right]};
            word[right] = word[left];
            word[left] = temp;
        }
    }

    // Проход 2: обычный побайтовый разворот всей строки целиком (классический цикл Праты)
    for (std::size_t j{0}, i{word.size()}; j < i; ++j)
    {
        --i;
        const char temp{word[i]};
        word[i] = word[j];
        word[j] = temp;
    }

    std::cout << std::format("{}\nГотово.\n", word);
}




