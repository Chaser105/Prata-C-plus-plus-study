/*
Как это работает на конкретных цифрах:

Допустим, в системе CLOCKS_PER_SEC равно 1000, а ввели 2 секунды:
1. delay = 2 * 1000 → программа запоминает, что нужно прождать 2000 тиков.
2. start = clock() → допустим, с момента запуска программы прошло 500 тиков. Записываем start = 500.
3. Запускается цикл while:
    • Прошла доля секунды: clock() возвращает 501. Считаем: 501 - 500 < 2000 (1 < 2000 — истина, крутимся дальше).
    • Прошла 1 секунда: clock() возвращает 1500. Считаем: 1500 - 500 < 2000 (1000 < 2000 — истина, крутимся дальше).
    • Прошло 2 секунды: clock() возвращает 2500. Считаем: 2500 - 500 < 2000 (2000 < 2000 — ложь!).
*/


// Стандарт С++20

#include <iostream>
#include <thread>                                           // Подключение заголовочного файла, где определены функции управления потоками, в том числе sleep_for();
#include <chrono>                                           // Подключение заголовочного файла, где определны такие типы, как seconds, milliseconds, microseconds;

int main()
{
    using namespace std::chrono;                            // Директива using namespace открывает доступ ко всем типам и функциям из вложенного пространства имен std::chrono без необходимости писать префикс std::chrono::
    std::cout << "Введите время задержки в секундах: ";

    float secs{};
    std::cin >> secs;

    const auto delay = milliseconds(static_cast<long long>(secs * 1000)); // Инициализация защищенной переменной автоматического типа (определится тип milliseconds).
                                                                          // Если переменная будет дробной, при умножении на 1000 делаем ее целой и явно приводим значение к целочисленному типу, т.к. тип milliseconds работает с целыми числами;
    std::cout << "запуск\n";
    std::this_thread::sleep_for(delay);                                   // Вложенное пространство имен this_thread, которое применяет функцию управления потоком sleep_for, принимающая переменную, содержащую значение, представляющее время на сколько нужно приостановить поток;

    std::cout << "Готово\n";
}



