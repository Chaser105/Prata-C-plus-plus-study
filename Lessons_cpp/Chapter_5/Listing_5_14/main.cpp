/*
 * КОНСПЕКТ: Потоки (std::thread) и современная задержка (C++11/20)
 *
 * 1. ПОТОК (Thread) — "повар", который построчно выполняет код программы.
 *    - При запуске любой программы ОС создает 1 главный поток (выполняет main()).
 *    - Параллельно (физически одновременно) работает столько потоков, сколько
 *      логических ядер у процессора.
 *    - Если потоков больше, чем ядер, ОС быстро переключает их по очереди (по ~10-15 мс),
 *      создавая иллюзию одновременной работы.
 *    - Создавать потоков можно тысячи (пока хватает ОЗУ: ~1-8 МБ стека на поток),
 *      но для тяжелых вычислений оптимально брать по числу ядер.
 *
 * 2. ПРОСТРАНСТВО ИМЕН std::this_thread — команды управления для ТЕКУЩЕГО потока:
 *    - sleep_for(время) — усыпляет текущий поток на заданный интервал.
 *      В этот момент код внутри потока стоит, но ядро процессора полностью
 *      освобождается для других задач ОС (нагрузка 0%).
 *
 * 3. ПОЧЕМУ НЕ ИСПОЛЬЗУЮТ while (clock() - start < delay) ИЗ УЧЕБНИКА:
 *    - Пустой цикл крутится миллионы раз в секунду, впустую нагружая ядро на 100%.
 *    - sleep_for + <chrono> делает ту же паузу без нагрузки на железо и без ручного
 *      перевода времени в системные тики (CLOCKS_PER_SEC).
 *
 * 4. ШПАРГАЛКА ПО <chrono> (работают с целыми числами):
 *    - Основные типы: hours, minutes, seconds, milliseconds, microseconds, nanoseconds.
 *    - Удобные суффиксы (C++14, при using namespace std::chrono_literals;):
 *      2h (часа), 10min (минут), 5s (секунд), 500ms (миллисекунд).
 *      Пример: std::this_thread::sleep_for(2s); // сон ровно на 2 секунды
 *    - Если время дробное (float/double), переводим в меньшие единицы через static_cast:
 *      milliseconds(static_cast<long long>(secs * 1000))
 */
