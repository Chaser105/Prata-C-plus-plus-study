// Стандарт С++20

#include <iostream>
#include <cstdint>
#include <format>

int main()
{
    constexpr std::int32_t guess_vol{7};

    std::int32_t n{0};
    std::cout << "Введите числа в диапазоне от 1 до 10, чтобы найти мое любимое число\n";
    do                                      // В цикле конструкции do while сначала выполняется блок операторов относящиеся к do, только затем проверяется условие данного цикла.
    {                                       // Если условие истино, программа возвразается вновь к блоку операторов do, в противном случае цикл завершается;
        std::cin >> n;
    } while (n != guess_vol);
    std::cout << std::format("Да, {} мое любимое число\n", guess_vol);
}



