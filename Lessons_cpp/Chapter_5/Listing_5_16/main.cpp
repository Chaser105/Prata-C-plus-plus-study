// Стандарт С++20

#include <iostream>
#include <format>
#include <string>

int main()
{
    std::string text{};                                        // Объявление объекта строки;

    std::cout << "Введите символы; введите # для выхода:\n";

    std::getline(std::cin, text, '#');              // Функция getline() с помощью объекта cin вводит строку, набранную с клавиатуры в объект строки, до тех пор, пока не введем символ '#';

    std::cout << std::format("\n{} символ(ов) прочтен(о)\n", text.size()); // На экран выведится сообщение о количестве прочитанных символов, определенное методом .size() класса string;
}


