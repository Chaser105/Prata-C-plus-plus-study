// Стандарт С++20

#include <iostream>
#include <format>
#include <cstdint>

int main()
{
    std::int32_t x{100};
    std::cout << std::format("Выражение x = 100 имеет значение {}\n", x);   // Объект cout выведет отформатированную строку со значением 100;

    std::cout << std::format("Выражение x < 3 имеет значение {:d}\n", (x < 3)); // Объект cout выведет отформатированную строку со значением 0 (булевое значение). Т.к. х не меньше 3, т.е. ложь;

    std::cout << std::format("Выражение x > 3 имеет значение {:d}\n", (x > 3)); // Объект cout выведет отформатированную строку со значением 1 (булевое значение). Т.к. х больше 3, т.е. истина;

    std::cout << std::format("Выражение x < 3 имеет значение {}\n", (x < 3));   // Объект cout выведет отформатированную строку со значением false (булевое значение). Т.к. х не меньше 3, т.е. ложь;

    std::cout << std::format("Выражение x > 3 имеет значение {}\n", (x > 3));   // Объект cout выведет отформатированную строку со значением true (булевое значение). Т.к. х больше 3, т.е. истина;
}


