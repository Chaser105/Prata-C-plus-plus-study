// Стандарт С++20

#include <iostream>
#include <string>
#include <format>
#include <cstddef>                             // Подключение заголовочного файла, где определен тип size_t;

int main()
{
    std::cout << "Введите слово: ";
    std::string word{};                        // Инициализация объекта строки класса string;
    std::getline(std::cin,word);         // Функция getline с помощью объекта cin вводит с клавиатуры строку в объект строки класса string;

    for (auto i{std::ssize(word) - 1}; i >= 0; --i) // Определение цикла for. 1 - инициализатор знакового типа (автоматически определяет тип long, т.к. функция ssize() для ОС Linux 64 разряда определяет объект как 64 битный тип), где переменной присваивается количество символов введенного слова, -1 делается, чтобы не выйти за границы строки, т.к. индекс идет не с 1, а с 0, 2 - выражение сравнения, 3 - выражение итерации с обратным отсчетом на 1 с каждым циклом;
        std::cout << std::format("{}",word[static_cast<std::size_t>(i)]);  // Когда значение счетчика цикла достигнет значения меньше 0, цикл завершится. word[static_cast<std::size_t>(i)] - индекс объекта строки явно приводится к беззнаковому типу, для безопасной работы программы, по причине того, что индекс не может быть отрицательным;

    std::cout << "\nГотово.\n";
}



