// Стандарт С++11:

#include <iostream>

int main()
{
    using namespace std;
    int quizscores[10] =                        // Инициализация массива из 10 элементов типа int;
        {20,20,20,20,20,19,20,18,20,20};
    cout << "Делаем как надо:\n";
    int i;
    for (i = 0; quizscores[i] == 20; i++)       // Определение цикла for. 1 - инициализация переменной счетчика. 2 - выражение сравнения. Каждый элемент массива сравнивается со значением 20. 3 - выражение итерации, с каждым циклом значение переменной увеличивается на 1;
        cout << "Опрос " << i << ": 20\n";     // Цикл остановится на значение 19, выведется 5 раз значение 20;

    // Так делать не надо:
    cout << "Так делать неверно:\n";
    for (i = 0; quizscores[i] = 20; i++)        // Определение цикла for. 1 - инициализация переменной счетчика. 2 - выражение присваивания (вместо сравнения). Каждому элементу массива присваивается значением 20. 3 - выражение итерации, с каждым циклом значение переменной увеличивается на 1;
        cout << "Опрос " << i << ": 20\n ";     // Т.к. вместо выражения сравнения в цикле for, происходит присваивание каждому элементу массива, более того в данном цикле отсутствует выражение для прекращения цикла (число 20 приравнивается к true), тем самым выходим за пределы массива и занчение 20 присваивается уже в чужую память.
    return 0;                                   // Из-за такой ошибки программа может уйти в бесконечность или пока не закончится память, завершиться с аварийным предупреждением;
}