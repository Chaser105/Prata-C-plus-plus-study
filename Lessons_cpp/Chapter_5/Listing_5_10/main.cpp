// Стандарт С++20

#include <iostream>
#include <format>
#include <array>                                        // Подключение заголовочного файла для работы с фиксированным классом-контейнером std::array, который четко определяет границы массива;
#include <cstddef>                                      // Подключение заголовочного файла, где определен тип size_t;
#include <cstdint>

int main()
{
    constexpr std::size_t SIZE{10};                     // Константа вычисляющаяся на этапе компиляции, которая задает размер массива;
    std::array<std::int32_t, SIZE> quizscores{20, 20, 20, 20, 20, 19, 20, 18, 20, 20}; // Безопасная инициализация массива;
    std::cout << "Делаем как надо:\n";
    for (std::size_t i = 0; quizscores[i] == 20; ++i)   // Определение цикла for. 1 - инициализация переменной-счетчика беззнакового типа. 2 - выражение сравнения. Каждый элемент массива сравнивается со значением 20. 3 - выражение итерации, с каждым циклом значение переменной увеличивается на 1;
        std::cout << std::format("Опрос {}: 20\n", i);

    // Так делать не надо:
    std::cout << "Так делать неверно:\n";
    for (std::size_t i = 0; quizscores[i] = 20; ++i)    // Определение цикла for. 1 - инициализация переменной-счетчика беззнакового типа. 2 - выражение присваивания (вместо сравнения). Каждому элементу массива присваивается значение 20. 3 - выражение итерации, с каждым циклом значение переменной увеличивается на 1;
        std::cout << std::format("Опрос {}: 20\n", i); // Вместо выражения сравнения в цикле for, происходит присваивание каждому элементу массива, более того в данном цикле отсутствует выражение для прекращения цикла (число 20 приравнивается к true), тем самым выходим за пределы массива и значение 20 присваивается уже в чужую память.
}                                                                 // Из-за такой ошибки программа может уйти в бесконечность или пока не закончится память, завершиться с аварийным предупреждением;



