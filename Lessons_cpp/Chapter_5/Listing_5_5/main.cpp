// Стандарт С++20

#include <iostream>
#include <format>
#include <cstdint>

int main()
{
    constexpr std::int32_t limit{100};                 // Константа известная еще на этапе компиляции;

    std::cout << "Введите целое число: ";
    std::int32_t by{0};                                // Безопасная инициализация переменной фиксированного типа значением по умолчанию для задания шага в цикле for;
    std::cin >> by;

    std::cout << std::format("Счет до {}\n", by);

    for (std::int32_t i{0}; (by > 0) && (i < limit); i += by)    // Определение цикла for. 1 - безопасный инициализатор фиксированного знакового типа, 2 - выражение сравнения. Защита от отрицательного значения, нуля и ограничение на выполнение цикла, 3 - выражение итерации с шагом, которое определяется выражением;
        std::cout << std::format("{}\n", i);          // Когда значение счетчика цикла станет больше или равно 100 цикл завершится;
}



