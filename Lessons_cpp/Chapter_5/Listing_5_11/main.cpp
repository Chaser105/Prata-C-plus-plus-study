// Стандарт С++20

#include <iostream>
#include <string>
#include <format>
#include <string_view>                                       // Подключение заголовочного файла для наложения взгляда на строку, также определения размера этой строки;

int main()
{
    constexpr std::string_view target{"mate"};            // Класс string_view() накладывает взгляд на инициализированную константную строку, которая вычисляется на этапе компиляции;
    std::string word{"?ate"};                              // Инициализация объекта строки строковым литералом;
    for (auto ch{'a'}; word != target && ch <= 'z'; ++ch) // Определение цикла for. 1 - инициализация переменной-счетчика автоматического типа (назначится типа char), которой присваивается символ 'a'. 2 - выражение сравнения. Если строка записанная в объект строки не равна константному объекту, результат будет true, если строки будут равны - false, тем самым цикл for завершится. Также стоит проверка границы символов, дальше буквы z цикл завершится;
    {                                                        // 3 - выражение итерации, в котором с каждой итерацией происходит переход на следующий символ согласно ASCII таблице;
        std::cout << std::format("{}\n",word);
        word.front() = ch;                                   // Первый символ строки с помощью метода .front класса std::string при каждой итерации будет перезаписываться значением ch;
    }
    std::cout << std::format("Вывод слова {} по завершению цикла.\n", word);
}



