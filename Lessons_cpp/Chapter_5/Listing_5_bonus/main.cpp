// Стандарт С++23/С++26

#include <print>
#include <array>

int main()
{
    // 1. Обычный обход массива:
    std::array prices{4.99, 10.99, 6.87, 7.99, 8.49};    // Инициализация массива, который автоматически определяет тип double, т.к. применены значения с плавающей точкой без применения суффикса f;
    double total{0.0};

    std::println("Чек:");

    for (const double price : prices)                    // Определение цикла for. Константной переменной типа double через ":" с каждой итерацией присваиваются по очереди элементы массива. После перебора всех элементов массива, цикл завершается, программа идет дальше;
    {
        std::println("Товар: {} $", price);
        total += price;                                  // Прибавляем текущую цену к общей сумме;
    }

    std::println("Итого к оплате: {:.2f} $\n", total);

    // 2. Изменение элементов массива через ссылку (&):
    for (double& price : prices)                         // Определение цикла for. Через ссылку price (благодаря "&") получаем прямой доступ к каждому элементу массива. В каждой итерации изменяем не копию, а оригинальный элемент массива;
                                                         // Ссылка double& price псевдоним очередного элемента массива prices;
    {
        price *= 0.80;                                   // применяем скидку 20% напрямую к каждому товару;
    }

    std::println("Цены после скидки 20%:");
    for (const double price : prices)                   // Определение цикла for. Константной переменной типа double через ":" с каждой итерацией присваиваются по очереди элементы массива. После перебора всех элементов массива, цикл завершается, программа идет дальше;
    {
        std::println("Товар со скидкой: {:.2f} $", price);
    }

    // 3. Обход списка инициализации прямо в заголовке цикла (без создания массива)
    std::print("\nНомера касс со скидками: ");
    for (const auto kassa : {3, 5, 2, 8, 6})         // Определение цикла for. Константной переменной автоматического типа (определится тип int, т.е. элементы целые без дополнительных суффиксов) через ":" с каждой итерацией присвиваются переменной по очереди списковые элементы, определенные с помощью  std::initializer_list<int> (списковая передачи набора значений);
    {                                                   // Цикл завершится когда перебирутся все элементы;
        std::print("{} ", kassa);
    }
    std::println();                                     // Перенос строки в конце;
}
