// Стандарт С++20

#include <iostream>
#include <format>
#include <cstdint>
#include <array>
#include <cstddef>                                               // Подключение заголовочного файла, где содержится применение типа size_t;

namespace                                                        // namespace - пространство имен, которое сообщает компилятору, что константа используется только в файле main.cpp, тем самым защищая от конфликтов имен в случае расширения программы;
{
    constexpr  std::size_t ar_size{16};                          // Константа известная еще на этапе компиляции программы;
}

int main()
{
    std::array<std::int64_t, ar_size> factorial{1, 1};           // Безопасная инициализация массива, содержащая 16 элементов типа int64_t. factorial{1, 1} - первым двум элементам массива присваивается 1, остальным нули;

    for (std::size_t i{2}; i < factorial.size(); ++i)            // Определение цикла for. 1 - инициализатор беззнакового типа, 2 - выражение сравнения счетчика цикла с размером массива, который определяется методом .size(), 3 - выражение итерации, увеличение значение переменной на 1;
        factorial[i] = static_cast<std::int64_t>(i) * factorial[i - 1];  // В каждом цикле вместо индекса подставляется текущее значение счетчика цикла. static_cast<std::int64_t>(i) - производится безопасное приведение к типу int64_t переменной i, т.к. изначально переменная имеет другой тип;

    for (std::size_t index{0}; const auto value : factorial)       // Определение цикла for. 1 - инициализатор беззнакового типа, 2 - выражение итерации. Объявляется константная переменная автоматического типа (компилятору сообщается, что нужно применить тип массива - int64_t), (:) означает, что необходимо перебрать все элементы по порядку от 0 до 15;
        std::cout << std::format("{}! = {}\n", index++, value);   // В каждом цикле вместо индекса подставляется значение счетчика, которое увеличивается на 1 с каждым циклом, и значение каждого элемента массива, которое выводит объект cout;
}



