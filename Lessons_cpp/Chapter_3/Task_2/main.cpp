// Стандарт С++20:

#include <iostream>
#include <format>                                                              // Подключение библиотеки для форматирования текста (стандарт C++20);
#include <cstdint>                                                             // Подключение типов данных с гарантированным фиксированным размером в битах;

constexpr int32_t Inches_Per_Foot{12};                                         // Константа времени компиляции со строго фиксированным типом данных (в одном футе 12 дюймов);
constexpr float Meters_Per_Inch{0.0254f};                                      // Коэффициент перевода: количество метров в одном американском дюйме;
constexpr float Pounds_Per_Kilogram{2.2f};                                     // Коэффициент перевода: количество фунтов в одном метрическом килограмме;

int main()
{
    int32_t height_feet{0}, height_inches{0};
    float weight{0.0f};                                                        // Безопасная списковая инициализация вещественной переменной веса нулем во избежание «мусора»;
    std::cout << "Введите рост в футах и в дюймах, а также вес в фунтах: ";    // Вывод приглашения к вводу в поток консоли напрямую без std::format ради экономии ресурсов;
    std::cin >> height_feet >> height_inches >> weight;                        // Каскадное извлечение трех параметров из консоли в соответствующие переменные;
    int32_t height = height_feet * Inches_Per_Foot + height_inches;            // Переводим комбинированный рост в чистые дюймы силами целочисленной арифметики;
    float total_height = static_cast<float>(height) * Meters_Per_Inch;         // Переводим дюймы в метры, аккуратно приведя целое число к типу float перед умножением;
    float weight_kilograms = weight / Pounds_Per_Kilogram;                     // Переводим дробный вес в фунтах в килограммы делением на коэффициент 2.2;
    float BMI = weight_kilograms / (total_height * total_height);              // Расчет индекса BMI делением массы на квадрат роста в метрах;
    std::cout << std::format("Индекс массы тела = {:.2f}\n", BMI);  // Вывод форматированной строки через std::format с округлением до 2 знаков;
}



